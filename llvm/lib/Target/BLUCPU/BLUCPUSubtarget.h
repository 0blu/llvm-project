#ifndef LLVM_BLUCPU_SUBTARGET_H
#define LLVM_BLUCPU_SUBTARGET_H

#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#include "BLUCPUFrameLowering.h"
#include "BLUCPUISelLowering.h"
#include "BLUCPUInstrInfo.h"
#include "BLUCPUSelectionDAGInfo.h"
#include "MCTargetDesc/BLUCPUMCTargetDesc.h"

#define GET_SUBTARGETINFO_HEADER
#include "BLUCPUGenSubtargetInfo.inc"

namespace llvm {

/// A specific BLUCPU target MCU.
class BLUCPUSubtarget : public BLUCPUGenSubtargetInfo {
public:
  //! Creates an BLUCPU subtarget.
  //! \param TT  The target triple.
  //! \param CPU The CPU to target.
  //! \param FS  The feature string.
  //! \param TM  The target machine.
  BLUCPUSubtarget(const Triple &TT, const std::string &CPU, const std::string &FS,
               const BLUCPUTargetMachine &TM);

  const BLUCPUInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const BLUCPUTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const BLUCPUSelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }
  const BLUCPURegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  /// Parses a subtarget feature string, setting appropriate options.
  /// \note Definition of function is auto generated by `tblgen`.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  BLUCPUSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS,
                                                const TargetMachine &TM);

  // Subtarget feature getters.
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool GETTER() const { return ATTRIBUTE; }
#include "BLUCPUGenSubtargetInfo.inc"

  uint8_t getIORegisterOffset() const { return 0x0; }

  bool enableSubRegLiveness() const override { return true; }

  /// Gets the ELF architecture for the e_flags field
  /// of an ELF object file.
  unsigned getELFArch() const {
    assert(ELFArch != 0 &&
           "every device must have an associate ELF architecture");
    return ELFArch;
  }

  /// Get I/O register addresses.
  int getIORegRAMPZ() const { return -1; }
  int getIORegEIND() const { return -1; }
  int getIORegSPL() const { return 0x3d; }
  int getIORegSPH() const { return 0x3e; }
  int getIORegSREG() const { return 0x3f; }

  /// Get GPR aliases.
  int getRegTmpIndex() const { return 0; }
  int getRegZeroIndex() const { return 1; }

  Register getTmpRegister() const {
    return BLUCPU::R0;
  }
  Register getZeroRegister() const {
    return BLUCPU::R1;
  }

private:
  /// The ELF e_flags architecture.
  unsigned ELFArch = 0;

  // Subtarget feature settings
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool ATTRIBUTE = DEFAULT;
#include "BLUCPUGenSubtargetInfo.inc"

  BLUCPUInstrInfo InstrInfo;
  BLUCPUFrameLowering FrameLowering;
  BLUCPUTargetLowering TLInfo;
  BLUCPUSelectionDAGInfo TSInfo;
};

} // end namespace llvm

#endif // LLVM_BLUCPU_SUBTARGET_H
