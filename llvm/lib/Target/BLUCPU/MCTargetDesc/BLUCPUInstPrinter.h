#ifndef LLVM_BLUCPU_INST_PRINTER_H
#define LLVM_BLUCPU_INST_PRINTER_H

#include "llvm/MC/MCInstPrinter.h"

#include "MCTargetDesc/BLUCPUMCTargetDesc.h"

namespace llvm {

/// Prints BLUCPU instructions to a textual stream.
class BLUCPUInstPrinter : public MCInstPrinter {
public:
  BLUCPUInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                 const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot, const MCSubtargetInfo &STI, raw_ostream &O) override;
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);

  // Autogenerated by TableGen.
  std::pair<const char *, uint64_t> getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &O);
  void printCustomAliasOperand(const MCInst *MI, uint64_t Address, unsigned OpIdx, unsigned PrintMethodIdx, raw_ostream &O);
  const char *getRegisterName(MCRegister Reg);
};

} // end namespace llvm

#endif // LLVM_BLUCPU_INST_PRINTER_H
